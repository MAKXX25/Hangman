// ── Dynamic Randomizer Utility ───────────────────────────────────────────────
/**
 * Picks a random phrase from an array, guaranteeing it is never identical
 * to previousPhrase consecutively (if the array has > 1 option).
 * 
 * @param {string[]} phraseArray - Array of comedic dialogue strings
 * @param {string} [previousPhrase] - The previous phrase spoken
 * @returns {string} A randomly selected phrase
 */
export function getRandomPhrase(phraseArray, previousPhrase = '') {
  if (!Array.isArray(phraseArray) || phraseArray.length === 0) return '';
  if (phraseArray.length === 1) return phraseArray[0];

  // Filter out previous phrase to guarantee no consecutive repetition
  const candidatePool = phraseArray.filter((phrase) => phrase !== previousPhrase);
  const pool = candidatePool.length > 0 ? candidatePool : phraseArray;

  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
